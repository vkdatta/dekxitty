// Regenerates ../registry.js from the catalog so the sidebar never needs the tool code at start-up.
import fs from "fs";
const { TOOLS } = await import("../catalog.js");
const rows = TOOLS.map((t) => `    ${JSON.stringify([t.id, t.name, t.group, t.icon, t.auto ? 1 : 0])}`).join(",\n");
export const source = `/* GENERATED by tests/build-registry.mjs — do not edit by hand. */
(function () {
  "use strict";
  // The modal engine and algorithms load on first use only.
  const UI = new URL("ui.js", document.currentScript.src).href;
  window.dexTool = function (id) {
    import(UI).then((m) => m.openTool(id)).catch((e) => { console.error(e); showNotification("Could not load the tool. Check your connection."); });
  };
  FunctionRegistry.registerLevel1({ id: "tools", name: "Tools", icon: "apps" });
  // [id, name, group, icon, automatable]
  [
${rows}
  ].forEach(([id, name, group, icon, auto]) => FunctionRegistry.register({
    function: "tool_" + id.replace(/-/g, "_"), name: name, icon: icon, under: ["tools", group],
    isAutomatable: auto === 1, onclick: "window.dexTool('" + id + "')"
  }));
})();
`;
if (process.argv[1] && process.argv[1].endsWith("build-registry.mjs")) { fs.writeFileSync(new URL("../registry.js", import.meta.url), source); console.log("registry.js:", TOOLS.length, "tools"); }
